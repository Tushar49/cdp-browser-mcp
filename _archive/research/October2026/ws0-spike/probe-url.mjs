import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { fileURLToPath } from 'url';
const distPath = fileURLToPath(new URL('./dist/index.js', import.meta.url));
const transport = new StdioClientTransport({ command: process.execPath, args: [distPath] });
const client = new Client({ name: 'probe', version: '0.0.1' });
await client.connect(transport);
const call = (name, args) => client.callTool({ name, arguments: args });
const textOf = (res) => (res.content ?? []).map((x) => x.text ?? '').join('\n');
const newTab = textOf(await call('tabs', { action: 'new' }));
const tabId = newTab.match(/\[([0-9A-F]{32})\]/)?.[1];
const spki = process.env.SPKI_B64;
const cred = process.env.CRED_ID;
const url = `http://localhost:8877/webauthn-rig.html?credId=${cred}&spki=${encodeURIComponent(spki)}`;
console.log('navigating to:', url);
await call('page', { action: 'goto', tabId, url });
await new Promise((r) => setTimeout(r, 2500));
const content = textOf(await call('page', { action: 'content', tabId }));
console.log('page content:\n' + content);
await call('page', { action: 'goto', tabId, url: 'about:blank' });
transport.close();
